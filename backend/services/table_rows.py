def cell_to_api(value: Any) -> Any:
    """PostgreSQL value -> JSON-friendly value."""
    if isinstance(value, Decimal):
        return int(value) if value == value.to_integral_value() else float(value)
    if isinstance(value, datetime):
        return format_timestamp(value)
    if isinstance(value, date):
        return value.isoformat()
    if isinstance(value, UUID):
        return str(value)
    if isinstance(value, (bytes, memoryview)):
        return bytes(value).hex()
    if isinstance(value, list):
        return [cell_to_api(item) for item in value]
    return value


def row_to_api(table: TableInfo, row: dict[str, Any]) -> TableRow:
    """A ``SELECT *`` row -> ``TableRow``. NULL cells are left out of ``data``;
    ``created_at`` / ``updated_at`` columns are lifted out of it."""
    key = table.primary_key
    data = {
        column.name: cell_to_api(row[column.name])
        for column in table.data_columns
        if column.name in row and row[column.name] is not None
    }
    return TableRow(
        id=cell_to_api(row[key.name]) if key else None,
        table_id=table.ref,
        data=data,
        created_at=format_timestamp(row["created_at"]) if isinstance(row.get("created_at"), datetime) else None,
        updated_at=format_timestamp(row["updated_at"]) if isinstance(row.get("updated_at"), datetime) else None,
    )


