"""Validate and coerce row payloads against a table's PostgreSQL columns.

The target type of every cell is the column's SQL type as read from the
catalog (``services/table_catalog.py``), so the same checks apply to user
tables and to any other table the row API exposes. The database constraints
remain the backstop; these checks exist to answer ``422`` with one message
per cell instead of a PostgreSQL error for the first bad value.
"""

from __future__ import annotations

from datetime import date, datetime
from decimal import Decimal
from typing import Any
from uuid import UUID

from psycopg.types.json import Jsonb

from db.mapping import format_timestamp
from models.tables import TableRow
from services.form_logic import is_empty_value
from services.table_catalog import ColumnInfo, ColumnKind, TableInfo
from services.values import (
    parse_bool,
    parse_date_string,
    parse_integer,
    parse_json,
    parse_number,
    parse_text,
    parse_text_list,
    parse_timestamp,
    parse_uuid,
)

_PARSERS = {
    "text": parse_text,
    "integer": parse_integer,
    "number": parse_number,
    "boolean": parse_bool,
    "date": parse_date_string,
    "timestamp": parse_timestamp,
    "json": parse_json,
    "text_array": parse_text_list,
    "uuid": parse_uuid,
}


class RowValidationError(ValueError):
    """One message per offending cell (or query parameter)."""

    def __init__(self, errors: dict[str, str], message: str = "Row failed validation") -> None:
        super().__init__(message)
        self.message = message
        self.errors = errors


def coerce_cell(column: ColumnInfo, value: Any, *, check_options: bool = True) -> tuple[Any, str | None]:
    """``value`` as the column's type, ready to be a query parameter.

    Empty input (``None``, blank text) becomes ``None`` - except for a
    ``NOT NULL`` text column, where blank text is stored as ``''`` (the only
    "empty" such a column can hold). ``check_options`` enforces a select
    column's allowed values (writes); filters compare case-insensitively and
    skip it. Returns ``(value, error)``.
    """
    if column.kind == "json":
        if value is None:
            return None, None
        return Jsonb(value), None
    if is_empty_value(value):
        if column.kind == "text" and not column.nullable and isinstance(value, str):
            return "", None
        return None, None
    parser = _PARSERS.get(column.kind)
    if parser is None:
        return None, f"column type {column.sql_type} is not supported by the row API"
    parsed, error = parser(value)
    if error:
        return None, error
    if check_options and column.options is not None and parsed not in column.options:
        return None, f"must be one of: {', '.join(column.options)}"
    return parsed, None


def validate_row(table: TableInfo, data: dict[str, Any], *, partial: bool) -> dict[str, Any]:
    """Cells to write, coerced, keyed by column name.

    ``partial=False`` (INSERT): every given cell is checked and every column
    that is ``NOT NULL`` without a default must be present.
    ``partial=True`` (PATCH): only the given cells are checked; ``None``
    clears a cell, which a ``NOT NULL`` column refuses.
    Raises :class:`RowValidationError` listing every problem.
    """
    errors: dict[str, str] = {}
    values: dict[str, Any] = {}
    for name, raw in data.items():
        column = table.column(name)
        if column is None:
            errors[name] = "is not a column of this table"
            continue
        if not column.writable:
            errors[name] = "is generated by the database and cannot be set"
            continue
        value, error = coerce_cell(column, raw)
        if error:
            errors[name] = error
        elif value is None and not column.nullable:
            errors[name] = "is required" if not partial else "cannot be cleared (required)"
        else:
            values[name] = value
    if not partial:
        for column in table.columns:
            if column.required_on_insert and column.name not in values and column.name not in errors:
                errors[column.name] = "is required"
    if errors:
        raise RowValidationError(errors)
    return values


def coerce_key(table: TableInfo, row_id: str) -> Any | None:
    """The primary-key value for a path parameter, or ``None`` if it cannot
    be one (``abc`` for an integer key)."""
    key = table.primary_key
    if key is None:
        return None
    value, error = coerce_cell(key, row_id)
    return None if error or value is None else value


