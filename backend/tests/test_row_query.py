def test_kind_mapping():
    assert kind_of("character varying", "varchar") == "text"
    assert kind_of("bigint", "int8") == "integer" and kind_of("numeric", "numeric") == "number"
    assert kind_of("ARRAY", "_text") == "text_array" and kind_of("ARRAY", "_int4") == "unknown"
    assert kind_of("bytea", "bytea") == "unknown"


def test_options_from_check_parses_postgres_renderings():
    assert options_from_check("CHECK ((status = ANY (ARRAY['Open'::text, 'Closed'::text])))") == ("status", ["Open", "Closed"])
    assert options_from_check("CHECK ((status = 'Open'::text))") == ("status", ["Open"])
    assert options_from_check("""CHECK (("select" = ANY (ARRAY['Owner''s'::text])))""") == ("select", ["Owner's"])
    assert options_from_check("CHECK ((cost >= (0)::numeric))") is None
    assert options_from_check("CHECK ((btrim(id) <> ''::text))") is None


def test_split_reference():
    assert split_reference("work-orders") is None
    assert split_reference("public.forms") == ("public", "forms")


# -- query string -------------------------------------------------------------------------

def test_parse_sort_and_filter_params():
    assert parse_sort_param("-cost, title,+due,,") == [
        RowSort(column="cost", direction="desc"), RowSort(column="title"), RowSort(column="due"),
    ]
    assert parse_sort_param(None) == []
    assert parse_filter_param("status:equals:Open") == RowFilter(column="status", operator="equals", value="Open")
    assert parse_filter_param("title:contains:a:b") == RowFilter(column="title", operator="contains", value="a:b")
    assert parse_filter_param("status:is_one_of:Open, Closed") == RowFilter(column="status", operator="is_one_of", value=["Open", "Closed"])
    assert parse_filter_param("notes:is_empty") == RowFilter(column="notes", operator="is_empty", value=None)
    with pytest.raises(RowValidationError):
        parse_filter_param("title")
    with pytest.raises(RowValidationError):
        parse_filter_param("title:frobnicate:x")


