def _col(name, kind="text", sql_type=None, nullable=True, has_default=False, writable=True, pk=False, options=None):
    return ColumnInfo(name, sql_type or kind, kind, nullable, has_default, writable, pk, options)


TABLE = TableInfo("t", "user_tables", "t", [
    _col("id", "integer", "bigint", nullable=False, has_default=True, writable=False, pk=True),
    _col("created_at", "timestamp", "timestamp with time zone", nullable=False, has_default=True),
    _col("updated_at", "timestamp", "timestamp with time zone", nullable=False, has_default=True),
    _col("title", nullable=False),
    _col("status", options=["Open", "Closed"]),
    _col("cost", "number", "numeric"),
    _col("due", "date"),
    _col("urgent", "boolean", nullable=False, has_default=True),
    _col("tags", "text_array", "text[]"),
    _col("meta", "json", "jsonb"),
    _col("blob", "unknown", "bytea"),
])


def _sql(composable) -> str:
    return composable.as_string(None)


# -- values ---------------------------------------------------------------------------

def test_value_parsers():
    assert values.parse_number("2.0") == (2, None) and values.parse_number(2.5) == (2.5, None)
    assert values.parse_number(True)[1] and values.parse_number("x")[1] and values.parse_number("inf")[1]
    assert values.parse_integer("3") == (3, None) and values.parse_integer(3.0) == (3, None)
    assert values.parse_integer(3.5) == (None, "must be a whole number")
    assert values.parse_bool(" True ") == (True, None) and values.parse_bool("yes")[1]
    assert values.parse_date_string(" 2026-02-01 ") == ("2026-02-01", None)
    assert values.parse_date_string("2026-02-30")[1].startswith("must be a valid date")
    assert values.parse_timestamp("2026-01-01T10:00:00Z") == (datetime(2026, 1, 1, 10, tzinfo=timezone.utc), None)
    assert values.parse_timestamp("2026-01-01T12:00:00+02:00")[0] == datetime(2026, 1, 1, 10, tzinfo=timezone.utc)
    assert values.parse_timestamp("2026-01-01")[0] == datetime(2026, 1, 1, tzinfo=timezone.utc)
    assert values.parse_timestamp("yesterday")[1] and values.parse_timestamp(5)[1]
    assert values.parse_text(5) == ("5", None) and values.parse_text(True) == ("true", None)
    assert values.parse_text({"a": 1})[1] == "must be text"
    assert values.parse_uuid("6F1C3A8E-0000-4000-8000-000000000000") == ("6f1c3a8e-0000-4000-8000-000000000000", None)
    assert values.parse_uuid("nope")[1]
    assert values.parse_text_list(["a", 1]) == (["a", "1"], None) and values.parse_text_list("a")[1]


def test_coerce_cell_by_kind():
    assert coerce_cell(TABLE.column("cost"), "12") == (12, None)
    assert coerce_cell(TABLE.column("status"), "Open") == ("Open", None)
    assert coerce_cell(TABLE.column("status"), "open") == (None, "must be one of: Open, Closed")
    assert coerce_cell(TABLE.column("status"), "open", check_options=False) == ("open", None)
    assert coerce_cell(TABLE.column("title"), "") == ("", None)          # NOT NULL text keeps ''
    assert coerce_cell(TABLE.column("status"), "") == (None, None)       # nullable text: empty is NULL
    assert coerce_cell(TABLE.column("tags"), ["a"]) == (["a"], None)
    json_value, error = coerce_cell(TABLE.column("meta"), {"a": [1]})
    assert isinstance(json_value, Jsonb) and error is None
    assert coerce_cell(TABLE.column("meta"), None) == (None, None)
    assert coerce_cell(TABLE.column("blob"), "x") == (None, "column type bytea is not supported by the row API")


def test_validate_row_insert_and_patch():
    assert validate_row(TABLE, {"title": "A", "cost": "1"}, partial=False) == {"title": "A", "cost": 1}
    with pytest.raises(RowValidationError) as info:
        validate_row(TABLE, {"id": 1, "nope": 2, "cost": "x"}, partial=False)
    assert info.value.errors == {
        "id": "is generated by the database and cannot be set",
        "nope": "is not a column of this table",
        "cost": "must be a number",
        "title": "is required",
    }
    assert validate_row(TABLE, {"cost": None}, partial=True) == {"cost": None}
    with pytest.raises(RowValidationError) as info:
        validate_row(TABLE, {"title": None}, partial=True)
    assert info.value.errors == {"title": "cannot be cleared (required)"}


def test_row_to_api_lifts_timestamps_and_drops_nulls():
    now = datetime(2026, 1, 1, tzinfo=timezone.utc)
    row = row_to_api(TABLE, {"id": 7, "created_at": now, "updated_at": now, "title": "A", "status": None,
                             "cost": None, "due": None, "urgent": False, "tags": ["x"], "meta": {"k": 1}, "blob": None})
    assert row.id == 7 and row.table_id == "t" and row.created_at == "2026-01-01T00:00:00.000Z"
    assert row.data == {"title": "A", "urgent": False, "tags": ["x"], "meta": {"k": 1}}


