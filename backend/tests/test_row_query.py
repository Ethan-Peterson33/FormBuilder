def _where(*filters: tuple, match="all", search=None):
    query = RowQuery(filters=[RowFilter(column=c, operator=o, value=v) for c, o, v in filters], match=match, search=search)
    where, params = build_where(TABLE, query)
    return (_sql(where) if where is not None else None), params


def test_filter_sql_per_kind():
    assert _where(("title", "equals", "a")) == ('(lower("title") = lower(%s))', ["a"])
    assert _where(("title", "not_equals", "a")) == ('(("title" IS NULL OR lower("title") <> lower(%s)))', ["a"])
    assert _where(("title", "contains", "50%_x")) == ('("title" ILIKE %s)', ["%50\\%\\_x%"])
    assert _where(("title", "starts_with", "a")) == ('("title" ILIKE %s)', ["a%"])
    assert _where(("title", "not_contains", "a")) == ('(("title" IS NULL OR NOT "title" ILIKE %s))', ["%a%"])
    assert _where(("title", "is_one_of", ["A", "B"])) == ('(lower("title") = ANY(%s))', [["a", "b"]])
    assert _where(("title", "is_empty", None)) == ('(("title" IS NULL OR btrim("title") = \'\'))', [])
    assert _where(("cost", "greater_than", "5")) == ('("cost" > %s)', [5])
    assert _where(("cost", "is_one_of", "1,2")) == ('("cost" = ANY(%s))', [[1, 2]])
    assert _where(("cost", "is_not_empty", None)) == ('(NOT "cost" IS NULL)', [])
    assert _where(("due", "on_or_before", "2026-01-01")) == ('("due" <= %s)', ["2026-01-01"])
    assert _where(("urgent", "is_checked", None)) == ('("urgent" IS TRUE)', [])
    assert _where(("urgent", "equals", "false")) == ('("urgent" = %s)', [False])
    assert _where(("tags", "contains", "x")) == ('(%s = ANY("tags"))', ["x"])
    assert _where(("tags", "is_empty", None)) == ('(("tags" IS NULL OR cardinality("tags") = 0))', [])
    assert _where(("meta", "is_not_empty", None)) == ('(NOT "meta" IS NULL)', [])
    assert _where(("created_at", "after", "2026-01-01T00:00:00Z"))[0] == '("created_at" > %s)'


def test_match_any_search_and_combination():
    where, params = _where(("title", "equals", "a"), ("cost", "equals", 1), match="any", search="x")
    assert where == '(lower("title") = lower(%s) OR "cost" = %s) AND ("title"::text ILIKE %s OR "status"::text ILIKE %s)'
    assert params == ["a", 1, "%x%", "%x%"]
    assert _where() == (None, [])
    assert _where(search="  ") == (None, [])


def test_invalid_filters_collect_every_problem():
    query = RowQuery(filters=[
        RowFilter(column="nope", operator="equals", value=1),
        RowFilter(column="cost", operator="contains", value="1"),
        RowFilter(column="meta", operator="equals", value="x"),
        RowFilter(column="due", operator="before", value="soon"),
        RowFilter(column="title", operator="is_one_of", value=[]),
        RowFilter(column="tags", operator="contains", value=None),
    ])
    with pytest.raises(RowValidationError) as info:
        build_where(TABLE, query)
    assert info.value.errors == {
        "filters[0]": "unknown column 'nope'",
        "filters[1]": "operator 'contains' cannot be used with a numeric column",
        "filters[2]": "operator 'equals' cannot be used with a jsonb column",
        "filters[3]": "value must be a date in YYYY-MM-DD format",
        "filters[4]": "needs at least one value",
        "filters[5]": "needs a text value",
    }


def test_order_by_adds_the_key_and_nulls_last():
    assert _sql(build_order_by(TABLE, RowQuery())) == '"id" ASC'
    assert _sql(build_order_by(TABLE, RowQuery(sort=[RowSort(column="cost", direction="desc"), RowSort(column="title")]))) == (
        '"cost" DESC NULLS LAST, "title" ASC NULLS LAST, "id" ASC'
    )
    assert _sql(build_order_by(TABLE, RowQuery(sort=[RowSort(column="id", direction="desc")]))) == '"id" DESC NULLS LAST'
    with pytest.raises(RowValidationError) as info:
        build_order_by(TABLE, RowQuery(sort=[RowSort(column="meta"), RowSort(column="x")]))
    assert info.value.errors == {"sort[0]": "cannot sort by a jsonb column", "sort[1]": "unknown column 'x'"}


def test_every_kind_has_operators_and_column_names_are_quoted():
    assert set(OPERATORS_BY_KIND) == {"text", "uuid", "integer", "number", "boolean", "date", "timestamp", "json", "text_array", "unknown"}
    hostile = TableInfo("t", "public", 'x"; DROP TABLE forms; --', [_col('a"; --', pk=False)])
    where, params = build_where(hostile, RowQuery(filters=[RowFilter(column='a"; --', operator="equals", value="v")]))
    assert _sql(where) == '(lower("a""; --") = lower(%s))' and params == ["v"]
